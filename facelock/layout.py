"""Sidebar navigation with a focused vault and camera workspace."""

from PySide6.QtCore import Qt, QSize
from PySide6.QtWidgets import (
    QAbstractItemView,
    QCheckBox,
    QComboBox,
    QFrame,
    QHBoxLayout,
    QLineEdit,
    QListWidget,
    QPushButton,
    QSizePolicy,
    QStackedWidget,
    QVBoxLayout,
    QWidget,
)
from .visuals import icon, VaultArt


def build(w, label):
    def button(text, callback, kind=None, name=None):
        b = QPushButton(text)
        if name:
            b.setObjectName(name)
        if kind:
            b.setIcon(icon(kind, "#182010" if name == "primary" else "#adb4be"))
            b.setIconSize(QSize(20, 20))
        b.clicked.connect(callback)
        b.setCursor(Qt.CursorShape.PointingHandCursor)
        return b

    central = QWidget()
    shell = QHBoxLayout(central)
    shell.setContentsMargins(0, 0, 0, 0)
    shell.setSpacing(0)
    sidebar = QFrame()
    sidebar.setObjectName("sidebar")
    sidebar.setFixedWidth(208)
    side = QVBoxLayout(sidebar)
    side.setContentsMargins(20, 32, 20, 24)
    side.setSpacing(10)
    logo = QHBoxLayout()
    mark = label("◈", "logoMark")
    logo.addWidget(mark)
    logo.addWidget(label("Face Lock", "brand"))
    logo.addStretch()
    side.addLayout(logo)
    side.addSpacing(36)
    side.addWidget(label("WORKSPACE", "eyebrow"))
    w.home_button = button("My folder", w.go_home, "folder", "nav")
    w.enroll_button = button("Set up my face", w.enroll, "face", "nav")
    w.sequence_button = button("Gesture locks", w.configure_sequence, "gesture", "nav")
    for b in (w.home_button, w.enroll_button, w.sequence_button):
        b.setCheckable(True)
        side.addWidget(b)
    side.addStretch()
    identity = QFrame()
    identity.setObjectName("identity")
    identity_layout = QVBoxLayout(identity)
    identity_layout.setContentsMargins(14, 14, 14, 14)
    identity_layout.addWidget(label("YOUR PROFILE", "eyebrow"))
    w.profile_label = label("Face setup needed", "subtle")
    identity_layout.addWidget(w.profile_label)
    side.addWidget(identity)
    local = label("●  On-device processing", "local")
    local.setToolTip(
        "Camera frames stay on this Mac. This face-only prototype is not tamperproof; see the guide for security details."
    )
    side.addSpacing(8)
    side.addWidget(local)
    shell.addWidget(sidebar)

    content = QWidget()
    layout = QVBoxLayout(content)
    layout.setContentsMargins(32, 28, 32, 20)
    layout.setSpacing(22)
    header = QHBoxLayout()
    title = QVBoxLayout()
    title.setSpacing(5)
    title.addWidget(label("YOUR PRIVATE SPACE", "eyebrow"))
    w.workspace_title = label("My folder", "pageTitle")
    title.addWidget(w.workspace_title)
    header.addLayout(title)
    header.addStretch()
    badge = label("LOCAL VAULT", "badge")
    header.addWidget(badge)
    layout.addLayout(header)

    w.pages = QStackedWidget()
    home = QWidget()
    home_layout = QVBoxLayout(home)
    home_layout.setContentsMargins(0, 0, 0, 0)
    home_layout.setSpacing(18)
    summary = QFrame()
    summary.setObjectName("heroPanel")
    summary_row = QHBoxLayout(summary)
    summary_row.setContentsMargins(28, 24, 20, 24)
    info = QVBoxLayout()
    info.setSpacing(12)
    w.state_badge = label("READY TO PROTECT", "section")
    info.addWidget(w.state_badge)
    w.vault_label = label("A home for your\nprivate files.", "hero")
    info.addWidget(w.vault_label)
    w.vault_hint = label("", "path")
    info.addWidget(w.vault_hint)
    w.source_note = label("", "subtle")
    info.addWidget(w.source_note)
    w.locked_controls = QWidget()
    w.locked_controls.setObjectName("heroActions")
    locked = QHBoxLayout(w.locked_controls)
    locked.setContentsMargins(0, 6, 0, 0)
    w.unlock_button = button("Unlock folder", w.unlock, "lock", "primary")
    w.recovery_button = button("Use recovery key", w.recover, None, "quiet")
    locked.addWidget(w.unlock_button)
    locked.addWidget(w.recovery_button)
    locked.addStretch()
    info.addWidget(w.locked_controls)
    w.setup_controls = QWidget()
    w.setup_controls.setObjectName("heroActions")
    setup = QHBoxLayout(w.setup_controls)
    setup.setContentsMargins(0, 6, 0, 0)
    w.create_button = button("Encrypt a folder", w.create, "folder", "primary")
    w.open_button = button("Choose encrypted folder", w.choose_vault, None, "secondary")
    setup.addWidget(w.create_button)
    setup.addWidget(w.open_button)
    setup.addStretch()
    info.addWidget(w.setup_controls)
    summary_row.addLayout(info, 1)
    w.vault_art = VaultArt()
    summary_row.addWidget(w.vault_art)
    home_layout.addWidget(summary)

    method = QFrame()
    method.setObjectName("method")
    method_row = QHBoxLayout(method)
    method_row.setContentsMargins(18, 14, 18, 14)
    glyph = label("◎", "methodGlyph")
    method_row.addWidget(glyph)
    method_text = QVBoxLayout()
    method_text.setSpacing(3)
    method_text.addWidget(label("Your unlock sequence", "cardTitle"))
    w.sequence_note = label("", "subtle")
    method_text.addWidget(w.sequence_note)
    method_row.addLayout(method_text, 1)
    method_row.addWidget(label("FACE + MOVEMENT", "eyebrow"))
    home_layout.addWidget(method)

    w.unlocked_panel = QFrame()
    w.unlocked_panel.setObjectName("panel")
    files = QVBoxLayout(w.unlocked_panel)
    files.setContentsMargins(20, 18, 20, 18)
    files.setSpacing(12)
    row = QHBoxLayout()
    row.addWidget(label("Your files", "cardTitle"))
    row.addStretch()
    w.open_folder_button = button("Open in Finder", w.open_folder, "folder", "secondary")
    w.lock_button = button("Lock folder", w.lock, "lock", "primary")
    row.addWidget(w.open_folder_button)
    row.addWidget(w.lock_button)
    files.addLayout(row)
    w.file_list = QListWidget()
    w.file_list.itemSelectionChanged.connect(w.refresh_export)
    files.addWidget(w.file_list, 1)
    exports = QHBoxLayout()
    w.export_button = button("Save a copy elsewhere…", w.export, None, "quiet")
    w.export_button.setToolTip("A readable copy outside this folder stays readable after locking.")
    exports.addWidget(w.export_button)
    w.remove_originals_button = button(
        "Remove matching original folder…", w.remove_existing_originals
    )
    exports.addWidget(w.remove_originals_button)
    exports.addStretch()
    files.addLayout(exports)
    home_layout.addWidget(w.unlocked_panel, 1)

    w.empty_panel = QFrame()
    w.empty_panel.setObjectName("panel")
    empty = QVBoxLayout(w.empty_panel)
    empty.setContentsMargins(24, 22, 24, 22)
    empty.setSpacing(20)
    empty.addWidget(label("One folder. Three simple steps.", "cardTitle"))
    steps = QHBoxLayout()
    steps.setSpacing(22)
    for number, title, description in [
        ("01", "Protect", "Encrypt the files inside your original folder."),
        ("02", "Perform", "Match your face and complete your gesture locks."),
        ("03", "Open", "Your files return to the same place. Lock when done."),
    ]:
        col = QVBoxLayout()
        col.setSpacing(10)
        col.addWidget(label(number, "stepNumber"))
        col.addWidget(label(title, "stepTitle"))
        col.addWidget(label(description, "subtle"))
        col.addStretch()
        steps.addLayout(col, 1)
    empty.addLayout(steps, 1)
    home_layout.addWidget(w.empty_panel, 1)
    w.pages.addWidget(home)

    scan = QWidget()
    scan_layout = QVBoxLayout(scan)
    scan_layout.setContentsMargins(0, 0, 0, 0)
    scan_layout.setSpacing(12)
    w.scan_title = label("Set up your face", "scanTitle")
    scan_layout.addWidget(w.scan_title)
    w.scan_help = label("Keep your face visible and follow the prompts.", "subtle")
    scan_layout.addWidget(w.scan_help)
    from .lock_strip import LockStrip

    w.lock_strip = LockStrip()
    scan_layout.addWidget(w.lock_strip)
    w.camera_view = label("Starting camera…", "camera")
    w.camera_view.setAlignment(Qt.AlignmentFlag.AlignCenter)
    w.camera_view.setSizePolicy(QSizePolicy.Policy.Ignored, QSizePolicy.Policy.Ignored)
    w.camera_view.setMinimumSize(450, 280)
    body = QHBoxLayout()
    body.setSpacing(16)
    body.addWidget(w.camera_view, 3)
    w.record_editor = QFrame()
    w.record_editor.setObjectName("panel")
    w.record_editor.setFixedWidth(264)
    editor = QVBoxLayout(w.record_editor)
    editor.setContentsMargins(16, 18, 16, 18)
    editor.setSpacing(10)
    editor.addWidget(label("Build your sequence", "cardTitle"))
    editor.addWidget(label("Capture a pose for each lock. Drag to reorder.", "subtle"))
    w.sequence_list = QListWidget()
    w.sequence_list.setMinimumHeight(78)
    w.sequence_list.setDragDropMode(QAbstractItemView.DragDropMode.InternalMove)
    editor.addWidget(w.sequence_list, 1)
    w.gesture_name = QLineEdit()
    w.gesture_name.setPlaceholderText("Name this pose")
    w.gesture_name.setMaxLength(80)
    editor.addWidget(w.gesture_name)
    checks = QHBoxLayout()
    w.use_hands, w.use_body = QCheckBox("Hands"), QCheckBox("Body")
    w.use_hands.setChecked(True)
    checks.addWidget(w.use_hands)
    checks.addWidget(w.use_body)
    editor.addLayout(checks)
    w.capture_button = button("Capture pose · 3s", w.capture_pose, None, "primary")
    editor.addWidget(w.capture_button)
    w.delete_step_button = button("Remove selected", w.delete_gesture_step, None, "quiet")
    editor.addWidget(w.delete_step_button)
    w.save_sequence_button = button("Save sequence", w.save_sequence, None, "secondary")
    editor.addWidget(w.save_sequence_button)
    body.addWidget(w.record_editor)
    scan_layout.addLayout(body, 1)
    controls = QHBoxLayout()
    w.camera_choice = QComboBox()
    w.camera_choice.addItems([f"Camera {i}" for i in range(4)])
    w.camera_choice.currentIndexChanged.connect(w.camera_changed)
    controls.addWidget(w.camera_choice)
    w.camera_button = button("Cancel scan", w.go_home, None, "quiet")
    controls.addWidget(w.camera_button)
    controls.addStretch()
    w.score_label = label("", "subtle")
    controls.addWidget(w.score_label)
    scan_layout.addLayout(controls)
    w.pages.addWidget(scan)
    layout.addWidget(w.pages, 1)
    status_frame = QFrame()
    status_frame.setObjectName("statusBar")
    status_layout = QHBoxLayout(status_frame)
    status_layout.setContentsMargins(0, 12, 0, 0)
    status_layout.addWidget(label("●", "statusDot"))
    w.status = label("Ready", "state")
    status_layout.addWidget(w.status, 1)
    layout.addWidget(status_frame)
    shell.addWidget(content, 1)
    w.setCentralWidget(central)

    def navigation(index):
        mode = w.current_scan_mode
        w.home_button.setChecked(index == 0)
        w.enroll_button.setChecked(index == 1 and mode in ("enroll", "preview"))
        w.sequence_button.setChecked(index == 1 and mode == "record")
        w.workspace_title.setText(
            "Gesture locks"
            if index == 1 and mode == "record"
            else "Face recognition"
            if index == 1
            else "My folder"
        )

    w.update_navigation = navigation
    w.pages.currentChanged.connect(navigation)
    navigation(0)
